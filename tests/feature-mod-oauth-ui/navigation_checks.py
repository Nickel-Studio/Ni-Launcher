"""Temporary login preserves identity, ignores cancelled replies and restores motion."""
from playwright.sync_api import expect


def verify_account_return(page, check, base_url):
    page.goto(base_url + '/tests/feature-mod-oauth-ui/home.html')
    page.wait_for_load_state('networkidle')
    home = page.locator('.home')
    expect(home.locator('.home__name')).to_have_text('Original Microsoft')
    page.emulate_media(reduced_motion='no-preference')

    def settle():
        expect(home.locator('.home__swap')).to_have_attribute('data-phase', 'in')
        page.wait_for_timeout(450)

    def add_account():
        settle()
        home.get_by_role('button', name='切换账号', exact=True).click()
        page.get_by_role('button', name='登录其他账号', exact=True).click()
        expect(home.get_by_role('button', name='返回', exact=True)).to_be_visible()
        settle()

    add_account()
    check('adding another account keeps original active identity', page.evaluate("window.__home.active() === 'msa'"))
    expect(home.locator('.launch-button')).to_be_disabled()
    back = home.get_by_role('button', name='返回', exact=True)
    tabs = home.locator('.home__accounts')
    check('return control is below the account tabs', back.bounding_box()['y'] >= tabs.bounding_box()['y'] + tabs.bounding_box()['height'])
    home.get_by_role('tab', name='皮肤站', exact=True).click()
    settle()
    check('temporary provider selection does not change saved preference', page.evaluate("window.__home.settings().accountType === 'microsoft' && window.__home.active() === 'msa'"))
    back.click()
    expect(home.locator('.home__name')).to_have_text('Original Microsoft')
    settle()
    check('return reuses the avatar/name reveal animation', home.locator('.home__swap').evaluate("n=>getComputedStyle(n).animationName") == 'home-swap-in')
    expect(back).to_have_count(0)

    add_account()
    home.get_by_role('button', name='使用 Microsoft 登录', exact=True).click()
    page.wait_for_function('typeof window.__home.resolveMsa === "function"')
    page.get_by_role('button', name='取消', exact=True).click()
    back.click()
    page.evaluate("window.__home.resolveMsa({status:'success',account:{id:'late-msa',type:'microsoft',name:'Late Microsoft',uuid:'4'.repeat(32)}})")
    settle()
    expect(home.locator('.home__name')).to_have_text('Original Microsoft')
    check('return ignores a late cancelled Microsoft result', page.evaluate("window.__home.active() === 'msa' && !window.__home.calls.some(c=>c.command==='accounts_upsert')"))

    page.evaluate("window.__home.select('a')")
    expect(home.locator('.home__name')).to_have_text('Alpha Player')
    expect(home.locator('.home__email')).to_have_count(0)
    check('persisted OAuth account hides email even when email is present', True)
    add_account()
    page.evaluate("window.__home.oauthMode='finish'")
    home.get_by_role('button', name='使用 Alpha Skin 登录', exact=True).click()
    page.wait_for_function('typeof window.__home.finish === "function"')
    page.get_by_role('button', name='取消', exact=True).click()
    back.click()
    page.evaluate("window.__home.finish({status:'account',account:{id:'late-oauth',type:'littleskin',name:'Late OAuth',server:'https://a.example',authMethod:'oauth2'}})")
    settle()
    expect(home.locator('.home__name')).to_have_text('Alpha Player')
    check('return ignores a late cancelled OAuth result', page.evaluate("window.__home.active() === 'alpha' && !window.__home.calls.some(c=>c.command==='accounts_upsert')"))

    page.evaluate("window.__home.select('b')")
    expect(home.locator('.home__name')).to_have_text('Beta Player')
    expect(home.locator('.home__email')).to_be_visible()
    check('classic account still displays email when OAuth is preferred', True)
    page.evaluate("window.__home.select('a')")
    expect(home.locator('.home__name')).to_have_text('Alpha Player')
    add_account()
    page.evaluate("window.__home.oauthMode='finish'; window.__home.pauseSave=true; window.__home.releaseSave=null")
    home.get_by_role('button', name='使用 Alpha Skin 登录', exact=True).click()
    page.wait_for_function('typeof window.__home.finish === "function"')
    page.evaluate("window.__home.finish({status:'account',account:{id:'new-oauth',type:'littleskin',name:'New OAuth',server:'https://a.example',authMethod:'oauth2'}})")
    page.wait_for_function('typeof window.__home.releaseSave === "function"')
    expect(back).to_be_disabled()
    check('return cannot race committed account persistence', page.evaluate("window.__home.active() === 'alpha'"))
    page.evaluate('window.__home.releaseSave()')
    expect(home.locator('.home__name')).to_have_text('New OAuth')
    expect(back).to_have_count(0)
    expect(home.locator('.home__email')).to_have_count(0)
    check('successful temporary login activates new OAuth identity', page.evaluate("window.__home.active() === 'new-oauth'"))
    page.emulate_media(reduced_motion='reduce')
